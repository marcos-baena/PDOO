package irrgarten;

/**
 * Enumeration representing possible movement directions in the game.
 * Used for player and monster movement within the labyrinth.
 */
public enum Directions {
    /** Move to the left */
    LEFT,
    
    /** Move to the right */
    RIGHT,
    
    /** Move upwards */
    UP,
    
    /** Move downwards */
    DOWN
}
